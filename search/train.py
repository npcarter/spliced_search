def setup_mp(rank, world_size): #Code blatantly stolen from the PyTorch DDP tutorial
  """
  Initializes the multiprocessing system so that we can train in parallel

  args:
    rank: our rank within the MP scheme
    world_size: Total number of ranks being run
  """

  #Configure to target whatever accelerator we're running on
  acc = torch.accelerator.current_accelerator()
  backend = torch.distributed.get_default_backend_for_device(acc)

  dist.init_process_group(backend, rank=rank, world_size=world_size)

def cleanup_mp(): #Again, stolen from the PyTorch DDP tutorail
  """
  Clean up our multiprocessing setup
  """
  dist.destroy_process_group()

def synchronize_device(device):
    if device.type == "cuda":
        torch.cuda.synchronize()
    elif device.type == "mps":
        torch.mps.synchronize()
    elif device.type == "cpu":
        pass # CPU operations are synchronous by default

def train(model, optimizer, loss_fn, loader, device):
  """ Runs the training loop for the specified model, optimizer, loss_model, and dataloader
      for one epoch
      args:
        model: the model to train
        optimizer: the optimizer to use in training
        loss_fn: the loss model to use
        loader: the dataloader to fetch data from
        device: the device to run training on
  """

  model.train()
  for batch_idx, (names, sequences, labels) in enumerate(loader):
    sequences_device = sequences.to(device, non_blocking=True)
    labels_device =labels.to(device, non_blocking=True)
    logits_device = model.forward(sequences_device)
    loss = loss_fn.forward(logits_device, labels_device)
    optimizer.zero_grad()
    loss.backward()
    torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
    optimizer.step()


def validate(model, loss_fn, loader, device):
  """ Runs the evaluation loop for the specified model, loss_model, and dataloader
      args:
        model: the model to train
        loss_fn: the loss model to use
        loader: the dataloader to fetch data from
        device: the device to run training on
  """
  model.eval()
  loss = 0.0

  for batch_idx, (names, sequences, labels) in enumerate(loader):
    with torch.no_grad(): #don't need gradients because not training
      sequences_device = sequences.to(device, non_blocking=True)
      labels_device =labels.to(device, non_blocking=True)
      logits_device = model.forward(sequences_device)
      loss += loss_fn.forward(logits_device, labels_device)

  return loss/(len(loader.dataset)/loader.batch_size) #average loss per sequence in validation set, as loss is already
# normalized to batchsize.

def create_model(args, device):
  """
  Creates and returns the model, optimizer, loss function, and DataLoader we'll use
  args:
    args: the argument data structure generated by argparser when the script was started
    device: The device the training will run on
  """
  if device.type != "cuda": #pinning memory isn't supported on mps
     pin_memory = False
  else:
     pin_memory = args.pin_memory

  the_dataset = trainloader.TrainDataset(args.traindb, sequence_length=args.sequence_length, name_length=args.name_length, device=device)
  loader = DataLoader(the_dataset, batch_size=args.batch_size, shuffle=args.shuffle, num_workers=max(args.num_workers, 1),
                                   pin_memory=pin_memory, drop_last=args.drop_last, prefetch_factor=args.prefetch_factor)

  validate_dataset = trainloader.TrainDataset(args.validatedb, sequence_length=args.sequence_length, name_length=args.name_length, device=device)
  validate_loader = DataLoader(validate_dataset, batch_size=args.batch_size, shuffle=args.shuffle, num_workers=max(args.num_workers, 1),
                                     pin_memory=pin_memory, drop_last=args.drop_last, prefetch_factor=args.prefetch_factor)
  model = TwoLayerFC(sequence_length=args.sequence_length).to(device)
  loss_fn = TiberiusLoss(use_f1 = args.use_f1, f1_factor=args.f1_factor)
  optimizer = torch.optim.Adam(model.parameters(), args.learning_rate)

  return model, optimizer, loss_fn, loader, validate_loader


def restore_from_checkpoint(called_args, device):
  file_name = called_args.restorefile
  print(f"Restoring state from {file_name}")
  checkpoint = torch.load(file_name, map_location=device, weights_only=False) #put the restored model on the right device for
  # where this code is running, regardless of where it was.

  args = checkpoint['args']
  model = TwoLayerFC(sequence_length = args.sequence_length)
  loss_fn = TiberiusLoss(use_f1 = args.use_f1, f1_factor = args.f1_factor)
  model.load_state_dict(checkpoint['model'])
  model.to(device)
  optimizer = torch.optim.Adam(model.parameters(), lr=args.learning_rate)
  optimizer.load_state_dict(checkpoint['optimizer'])
  the_dataset = trainloader.TrainDataset(args.traindb, sequence_length=args.sequence_length, name_length=args.name_length, device=device)
  loader = DataLoader(the_dataset, batch_size=args.batch_size, shuffle=args.shuffle, num_workers=args.num_workers,
                                   pin_memory=args.pin_memory and device.type=="cuda", drop_last=args.drop_last)#, prefetch_factor=args.prefetch_factor)

  validate_dataset = trainloader.TrainDataset(args.validatedb, sequence_length=args.sequence_length, name_length=args.name_length, device=device)
  validate_loader = DataLoader(validate_dataset, batch_size=args.batch_size, shuffle=args.shuffle, num_workers=max(args.num_workers, 1),
                                     pin_memory=pin_memory, drop_last=args.drop_last, prefetch_factor=args.prefetch_factor)
  return(model, optimizer, loss_fn, loader, validate_loader, checkpoint['epoch']+1, args.epochs)

   
def save_checkpoint(model, optimizer, epoch, args, device):
  """
  Saves a checkpoint of training progress.
  """

  checkpoint = {
      'epoch': epoch, #How many epochs have we trained so far
      'model': model.state_dict(), #model's parameters
      'optimizer': optimizer.state_dict(), 
      'model_desc': 'put a real description here when we start juggling different models',
      'args': args
    }
  
  save_path = ""
  file_name = "checkpoint"+str(epoch)+".tar" #This is the PyTorch convention that checkpoint dictionaries
  #get named like they were tar files, in spite of the fact that they aren't in that format
  if args.checkpointdir[-1]=='/': 
     save_path = args.checkpointdir + file_name
  else:
     save_path = args.checkpointdir + '/'+ file_name
  
  torch.save(checkpoint, save_path)
  print(f"Saved checkpoint to {save_path}")

  #self-test
  new_args = copy.copy(args)
  new_args.restore=True
  new_args.restorefile=save_path
  new_model, new_optimizer, new_loss, new_loader, new_epoch, new_end = restore_from_checkpoint(new_args, device)
  #now compare the models
  assert new_model.state_dict().keys() == model.state_dict().keys(), "Restored model did not have same keys as saved"
  for key_item_new, key_item_old in zip(new_model.state_dict().items(), model.state_dict().items()):
    assert torch.equal(key_item_new[1], key_item_old[1]), f"restored model did not match saved weights at item {key_item_new[0]}"
  assert epoch == new_epoch -1, f"restored epoch {new_epoch-1} didn't match saved epoch {epoch}" #Should start at the next epoch
  assert new_end == args.epochs, f"Restored end epoch {new_end} didn't match saved {args.epochs}"

  assert new_optimizer.state_dict().keys() == optimizer.state_dict().keys(), "Restored optimizer had different key list than saved"
  old_sd, new_sd = optimizer.state_dict(), new_optimizer.state_dict()
  assert old_sd['param_groups'] == new_sd['param_groups'], "Restored optimizer hyperparameters differ from saved"
  assert old_sd['state'].keys() == new_sd['state'].keys(), "Restored optimizer has different parameter list than saved"
  for idx, old_state in old_sd['state'].items():
    new_state = new_sd['state'][idx]
    for name, old_t in old_state.items():
      assert torch.equal(old_t, new_state[name].to(old_t.device)), f"Restored optimizer {name} differs for param {idx}"

def main(args):
  """
  Main function.  Either creates the model, loss function, optimizer, etc. or loads them from checkpoint, 
  and then calls train()
  """
  wandb.login() 

  #check for a checkpoint directory if we need one
  if args.checkpoint and args.checkpointdir == None:
    raise ValueError("Checkpointing was specified without a checkpoint directory to store checkpoints in")

  if args.checkpoint: #make sure we have a directory to write checkpoint files to
    dir_path = Path(args.checkpointdir)
    dir_path.mkdir(parents=True, exist_ok =True)

  device = torch.device("cuda" if torch.cuda.is_available() else "mps" if torch.backends.mps.is_available() else "cpu")

  start_epoch = 0
  end_epoch = args.epochs
  #either create a new model or restore from checkpoint
  if args.restore == False: #just starting, create everything
    model, optimizer, loss_fn, loader, validate_loader= create_model(args, device)
  else:
    #restore from checkpoint
    model, optimizer, loss_fn, loader, validate_loader, start_epoch, end_epoch = restore_from_checkpoint(args, device)

  # then train
  with wandb.init(project="gene-finding") as run:
    for epoch in range(start_epoch, end_epoch):    

      train(model, optimizer, loss_fn, loader, device)

      loss = validate(model, loss_fn, validate_loader, device)

      if args.checkpoint and (epoch % args.checkpoint_interval == 0):
        save_checkpoint(model, optimizer, epoch, args, device)
      run.log({"Loss": loss})
      print(f"Loss after epoch {epoch} was {loss}")

#Hack to make main() only be called the first time the script is run, not when multiprocess creates instances
if __name__=='__main__':
  main(args)




